def _svg(name, color):
    path = PATHS.get(name, PATHS["note"])
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">'
            f'<path fill="{color}" d="{path}"/></svg>').encode("utf-8")


def pixmap(name, color="#ececef", size=24, dpr=2.0):
    key = (name, color, size, dpr)
    pm = _cache.get(key)
    if pm is not None:
        return pm
    px = int(size * dpr)
    image = QImage(px, px, QImage.Format_ARGB32_Premultiplied)
    image.fill(Qt.transparent)
    renderer = QSvgRenderer(QByteArray(_svg(name, color)))
    painter = QPainter(image)
    painter.setRenderHint(QPainter.Antialiasing)
    renderer.render(painter, QRectF(0, 0, px, px))
    painter.end()
    pm = QPixmap.fromImage(image)
    pm.setDevicePixelRatio(dpr)
    _cache[key] = pm
    return pm


def icon(name, color="#ececef", size=24):
    ic = QIcon()
    ic.addPixmap(pixmap(name, color, size), QIcon.Normal)
